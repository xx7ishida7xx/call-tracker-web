-- ============================================================================
-- call-tracker: 通話を記録したメンバーを、担当者が空のリードの担当者に自動で割り振る
--
-- 「通話を記録する」で結果を押すと、ステータスが自動で変わる（例：留守→架電中）のと
-- 同じように、そのリードの担当者が「未割当」だった場合は、記録した本人が担当者になる。
-- すでに担当者が決まっているリードは、誰が通話を記録しても担当者は変えない。
--
-- 通話記録を削除したときに、この自動割り振りも元に戻せるよう（ステータスの自動復元と同じ考え方）、
-- 「この通話の記録によって担当者が自動で割り振られたか」を通話記録自体に控えておく。
-- 削除時は、アプリ側（app/actions.ts の deleteCall）が、そのリードに通話記録が1件も
-- 残らず、担当者がまだ記録者本人のままであれば、担当者を「未割当」に戻す。
--
-- この変更より前の通話記録は false のまま（削除しても担当者は自動では戻らない）。
-- ============================================================================
alter table public.calls
  add column if not exists assigned_by_call boolean not null default false;

comment on column public.calls.assigned_by_call is
  'この通話の記録によって、未割当だったリードの担当者が記録者に自動で割り振られた場合 true。通話記録の削除時に担当者を戻すために使う。';
