-- ============================================================================
-- call-tracker: 通話記録を削除したときに、リードのステータスを自動で元に戻す
--
-- 通話を記録すると、結果に応じてリードのステータスが自動で変わる
-- （例：留守→架電中）。これまで、通話記録を削除しても最終架電などは戻るが、
-- ステータスは変わったままで、手動で戻す必要があった（戻し忘れの原因）。
--
-- そこで、通話を記録した時点の「記録する前のステータス」と「記録によって設定された
-- ステータス」を、通話記録自体に控えておく列を追加する。
-- 削除時は、アプリ側（app/actions.ts の deleteCall）が、一番新しい通話を削除した場合に
-- ステータスを「記録する前」に戻す（手動で変更済みの場合は何もしない）。
--
-- この変更より前の通話記録は、この2列が空のまま（削除してもステータスは自動では戻らない）。
-- ============================================================================
alter table public.calls
  add column if not exists status_before text,
  add column if not exists status_after text;

comment on column public.calls.status_before is
  'この通話を記録する直前のリードのステータス。通話記録の削除時にステータスを戻すために使う。';
comment on column public.calls.status_after is
  'この通話の記録によって設定されたリードのステータス。削除時に「その後に手動で変更されていないか」の確認に使う。';
